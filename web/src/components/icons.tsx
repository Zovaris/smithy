// TOOL_ICON picks an icon by what a tool does.
export function toolIcon(name: string): string {
  const n = name.toLowerCase();
  if (/edit|write|patch|apply|replace/.test(n)) return "pen";
  if (/bash|shell|exec|run|command/.test(n)) return "term";
  if (/grep|glob|search|find|ls/.test(n)) return "search";
  if (/fetch|web|http/.test(n)) return "globe";
  return "file";
}
