package p

import "strconv"

// FizzBuzz returns the FizzBuzz sequence from 1 to n.
func FizzBuzz(n int) []string {
	out := []string{}
	for i := 1; i <= n; i++ {
		switch {
		case i%15 == 0:
			out = append(out, "FizzBuzz")
		case i%3 == 0:
			out = append(out, "Fizz")
		case i%5 == 0:
			out = append(out, "Buzz")
		default:
			out = append(out, strconv.Itoa(i))
		}
	}
	return out
}
